import { build } from 'esbuild';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const nodeModules = join(backendRoot, 'node_modules');
const runtimeDeps = join(backendRoot, 'src', 'runtime-deps', 'node_modules');

function copyPackageTree(name, seen = new Set()) {
  if (seen.has(name) || name === 'pg-native') return;
  seen.add(name);

  const from = join(nodeModules, name);
  if (!existsSync(from)) {
    throw new Error(`Cannot stage ${name} for Vercel: missing ${from}`);
  }

  cpSync(from, join(runtimeDeps, name), { recursive: true, dereference: true });

  const pkg = JSON.parse(readFileSync(join(from, 'package.json'), 'utf8'));
  for (const dep of Object.keys(pkg.dependencies ?? {})) {
    copyPackageTree(dep, seen);
  }
}

rmSync(join(backendRoot, 'src', 'runtime-deps'), { recursive: true, force: true });
mkdirSync(runtimeDeps, { recursive: true });
copyPackageTree('argon2');

const linuxGlibc = join(runtimeDeps, 'argon2', 'prebuilds', 'linux-x64', 'argon2.glibc.node');
if (!existsSync(linuxGlibc)) {
  throw new Error(`Missing staged Linux x64 glibc argon2 prebuild: ${linuxGlibc}`);
}
const linuxGlibcBytes = readFileSync(linuxGlibc);
if (linuxGlibcBytes.subarray(0, 4).toString('hex') !== '7f454c46') {
  throw new Error(`Staged argon2 Linux prebuild is not an ELF binary: ${linuxGlibc}`);
}
const gyp = createRequire(import.meta.url)('node-gyp-build/node-gyp-build.js');
const linuxTags = gyp.parseTags('argon2.glibc.node');
if (!gyp.matchTags('node', '127')(linuxTags) || linuxTags.libc !== 'glibc') {
  throw new Error(`node-gyp-build would reject argon2.glibc.node for Node ABI 127 glibc: ${JSON.stringify(linuxTags)}`);
}
console.log(
  'STAGED_ARGON2_NATIVE',
  linuxGlibc,
  'bytes=' + String(statSync(linuxGlibc).size),
  'elf=linux',
  'node-gyp-build-abi127=' + String(Boolean(gyp.matchTags('node', '127')(linuxTags))),
);

const argon2Entry = join(runtimeDeps, 'argon2', 'argon2.cjs');

await build({
  absWorkingDir: backendRoot,
  entryPoints: ['src/vercel-server.ts'],
  outfile: 'src/englishine-app.mjs',
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  plugins: [
    {
      name: 'stub-optional-pg-native',
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^pg-native$/ }, () => ({
          path: 'optional-pg-driver',
          namespace: 'optional-empty',
        }));
        pluginBuild.onResolve({ filter: /^\.\/native(?:\.js)?$/ }, (args) => {
          const importer = args.importer.split('\\').join('/');
          if (!importer.includes('/pg/lib/')) return;
          return { path: 'optional-pg-driver', namespace: 'optional-empty' };
        });
        pluginBuild.onLoad({ filter: /.*/, namespace: 'optional-empty' }, () => ({
          contents: 'module.exports = null;',
          loader: 'js',
        }));
      },
    },
    {
      name: 'vercel-runtime-deps',
      setup(pluginBuild) {
        pluginBuild.onResolve({ filter: /^argon2$/ }, () => {
          const rel = `./${relative(join(backendRoot, 'src'), argon2Entry).split('\\').join('/')}`;
          return { path: rel, external: true };
        });
      },
    },
  ],
  banner: {
    js: '// Generated by scripts/bundle-vercel-server.mjs. Do not edit.\n',
  },
  logLevel: 'info',
});

const bundled = readFileSync(join(backendRoot, 'src', 'englishine-app.mjs'), 'utf8');
if (bundled.includes('pg-native')) {
  throw new Error('englishine-app.mjs still contains pg-native; optional native pg driver leaked into the bundle');
}
