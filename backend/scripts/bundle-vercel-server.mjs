import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  absWorkingDir: backendRoot,
  entryPoints: ['src/start-englishine-server.ts'],
  outfile: 'src/englishine-app.mjs',
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  packages: 'external',
  legalComments: 'none',
  banner: {
    js: '// Generated by scripts/bundle-vercel-server.mjs. Do not edit.\n',
  },
  logLevel: 'info',
});
