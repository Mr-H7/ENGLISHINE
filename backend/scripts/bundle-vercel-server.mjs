import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  absWorkingDir: backendRoot,
  entryPoints: ['src/vercel-server.ts'],
  outfile: 'src/englishine-app.mjs',
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  // Native addons stay external. ESM-only JS (file-type, Fastify 5) is inlined
  // so a later CJS rewrite cannot require() those packages.
  external: ['argon2', 'pg', 'pg-native'],
  banner: {
    js: '// Generated by scripts/bundle-vercel-server.mjs. Do not edit.\n',
  },
  logLevel: 'info',
});
